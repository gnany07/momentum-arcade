class Wordle {
    constructor() {
        // Full 10,000 most common 5-letter English words (ranked by frequency)
        this.wordList = WORDLE_COMMON_10000;
        this.validWordSet = new Set(this.wordList);
        // Curated everyday common 5-letter words for secret target selection
        this.answerPool = this.wordList.slice(0, 2315);

        this.currentWord = "";
        this.guesses = [];
        this.currentGuess = "";
        this.maxGuesses = 6;
        this.gameOver = false;
        this.isPlaying = false;
        this.played = 0;
        this.streak = 0;
        this.strictClueMode = true;
        this.revealedIndices = new Set();
        this.clueShown = false;

        this.board = document.getElementById("wordleBoard");
        this.keyboard = document.getElementById("wordleKeyboard");
        this.cluePanel = document.getElementById("wordleCluePanel");
        this.cluePatternEl = document.getElementById("wordleCluePattern");
        this.clueTextEl = document.getElementById("wordleClueText");
        this.validCountEl = document.getElementById("wordleValidCount");

        const startBtn = document.getElementById("startWordle");
        if (startBtn) startBtn.addEventListener("click", () => this.startGame());

        const newBtn = document.getElementById("newWordle");
        if (newBtn) newBtn.addEventListener("click", () => this.newGame());

        const hintBtn = document.getElementById("wordleHintBtn");
        if (hintBtn) hintBtn.addEventListener("click", () => this.revealClue());

        const strictBtn = document.getElementById("wordleStrictBtn");
        if (strictBtn) strictBtn.addEventListener("click", () => this.toggleStrictClueMode());

        document.addEventListener("keydown", this.handleKeyPress.bind(this));

        this.loadStats();
        this.showStartScreen();

        if (window.arcadeApp) {
            window.arcadeApp.registerGame("wordle", this);
        }
    }

    loadStats() {
        if (window.ScoreStorage) {
            window.ScoreStorage.get("wordlePlayed", (p) => {
                this.played = p || 0;
                const el = document.getElementById("wordlePlayed");
                if (el) el.textContent = this.played;
            });
            window.ScoreStorage.get("wordleStreak", (s) => {
                this.streak = s || 0;
                const el = document.getElementById("wordleStreak");
                if (el) el.textContent = this.streak;
            });
        }
    }

    showStartScreen() {
        if (this.board) {
            this.board.innerHTML = '<div style="grid-column: span 5; text-align: center; color: #94a3b8; padding: 2rem 0; font-size: 1.05rem;">Click <b>Start Game</b> to play Wordle!</div>';
        }
        if (this.keyboard) {
            this.keyboard.style.display = "none";
        }
        if (this.cluePanel) {
            this.cluePanel.classList.add("hidden");
        }
    }

    startGame() {
        this.isPlaying = true;
        if (this.keyboard) this.keyboard.style.display = "flex";
        if (this.cluePanel) this.cluePanel.classList.add("hidden");
        this.initializeBoard();
        this.initializeKeyboard();
        this.newGame();
    }

    pause() {
        if (this.isPlaying && !this.gameOver && typeof wordleTimer !== "undefined") {
            wordleTimer.stop();
        }
    }

    toggleStrictClueMode() {
        this.strictClueMode = !this.strictClueMode;
        const btn = document.getElementById("wordleStrictBtn");
        if (btn) {
            btn.classList.toggle("active-mode", this.strictClueMode);
            btn.textContent = this.strictClueMode ? "🛡️ Clue Check: ON" : "🛡️ Clue Check: OFF";
        }
        if (window.showToast) {
            window.showToast(
                this.strictClueMode
                    ? "Clue Validation ON: Guesses must match revealed clues!"
                    : "Clue Validation OFF: Any valid dictionary word allowed.",
                this.strictClueMode ? "🛡️" : "🔓"
            );
        }
    }

    initializeBoard() {
        this.board.innerHTML = "";
        for (let i = 0; i < this.maxGuesses; i++) {
            const row = document.createElement("div");
            row.className = "wordle-row";
            for (let j = 0; j < 5; j++) {
                const cell = document.createElement("div");
                cell.className = "wordle-cell";
                row.appendChild(cell);
            }
            this.board.appendChild(row);
        }
    }

    initializeKeyboard() {
        const keyboardLayout = [
            ["Q", "W", "E", "R", "T", "Y", "U", "I", "O", "P"],
            ["A", "S", "D", "F", "G", "H", "J", "K", "L"],
            ["↵", "Z", "X", "C", "V", "B", "N", "M", "⌫"]
        ];

        this.keyboard.innerHTML = "";
        keyboardLayout.forEach(row => {
            const keyboardRow = document.createElement("div");
            keyboardRow.className = "keyboard-row";

            row.forEach(key => {
                const keyElement = document.createElement("div");
                keyElement.className = "key";
                keyElement.textContent = key;

                if (key === "↵") {
                    keyElement.classList.add("enter-key");
                } else if (key === "⌫") {
                    keyElement.classList.add("backspace-key");
                }

                keyElement.addEventListener("click", () => this.handleKeyClick(key));
                keyboardRow.appendChild(keyElement);
            });

            this.keyboard.appendChild(keyboardRow);
        });
    }

    newGame() {
        if (!this.isPlaying) {
            this.startGame();
            return;
        }

        this.currentWord = this.answerPool[Math.floor(Math.random() * this.answerPool.length)];
        this.guesses = [];
        this.currentGuess = "";
        this.gameOver = false;
        this.revealedIndices = new Set();
        this.clueShown = false;

        // Keep clue panel hidden until the player explicitly clicks "💡 Clue"
        if (this.cluePanel) {
            this.cluePanel.classList.add("hidden");
        }

        if (typeof wordleTimer !== "undefined") {
            wordleTimer.reset();
            wordleTimer.start();
        }

        const cells = document.querySelectorAll(".wordle-cell");
        cells.forEach(cell => {
            cell.textContent = "";
            cell.className = "wordle-cell";
        });

        const keys = document.querySelectorAll(".key");
        keys.forEach(key => {
            key.className = "key";
            if (key.textContent === "↵") key.classList.add("enter-key");
            if (key.textContent === "⌫") key.classList.add("backspace-key");
        });

        this.updateClueAndValidationUI();
        if (window.sounds) window.sounds.launch();
    }

    // Compute a natural clue description for the current secret word
    getWordBaseClue() {
        if (!this.currentWord) return "";
        const vowels = (this.currentWord.match(/[AEIOU]/g) || []).length;
        const uniqueCount = new Set(this.currentWord.split("")).size;
        const repeatInfo = uniqueCount === 5 ? "No repeating letters" : "Has repeating letters";
        return `${vowels} ${vowels === 1 ? "vowel" : "vowels"} • ${repeatInfo}`;
    }

    // Build the consolidated clue constraints from all prior guesses and revealed hint positions
    getClueState() {
        const exactPositions = [null, null, null, null, null];
        const forbiddenPositions = [new Set(), new Set(), new Set(), new Set(), new Set()];
        const minLetterCounts = {};
        const maxLetterCounts = {};

        // 1. Include any explicitly revealed hint indices
        this.revealedIndices.forEach(idx => {
            const letter = this.currentWord[idx];
            if (letter) {
                exactPositions[idx] = letter;
                minLetterCounts[letter] = Math.max(minLetterCounts[letter] || 0, 1);
            }
        });

        // 2. Derive Green, Yellow, and Gray clue constraints from every submitted guess
        this.guesses.forEach(guess => {
            const targetCounts = {};
            for (let i = 0; i < 5; i++) {
                const ch = this.currentWord[i];
                targetCounts[ch] = (targetCounts[ch] || 0) + 1;
            }

            const status = ["absent", "absent", "absent", "absent", "absent"];
            const matchedCounts = {};

            // Exact (Green) matches first
            for (let i = 0; i < 5; i++) {
                if (guess[i] === this.currentWord[i]) {
                    status[i] = "correct";
                    exactPositions[i] = guess[i];
                    targetCounts[guess[i]]--;
                    matchedCounts[guess[i]] = (matchedCounts[guess[i]] || 0) + 1;
                }
            }

            // Present (Yellow) vs Absent (Gray) matches
            for (let i = 0; i < 5; i++) {
                if (status[i] !== "correct") {
                    const gChar = guess[i];
                    forbiddenPositions[i].add(gChar);
                    if (this.currentWord.includes(gChar) && targetCounts[gChar] > 0) {
                        status[i] = "present";
                        targetCounts[gChar]--;
                        matchedCounts[gChar] = (matchedCounts[gChar] || 0) + 1;
                    } else {
                        status[i] = "absent";
                    }
                }
            }

            // Update minLetterCounts and maxLetterCounts per letter in this guess
            const guessLetterTotals = {};
            for (let i = 0; i < 5; i++) {
                const gChar = guess[i];
                guessLetterTotals[gChar] = (guessLetterTotals[gChar] || 0) + 1;
            }

            Object.keys(guessLetterTotals).forEach(letter => {
                const positiveCount = matchedCounts[letter] || 0;
                if (positiveCount > 0) {
                    minLetterCounts[letter] = Math.max(minLetterCounts[letter] || 0, positiveCount);
                }
                if (guessLetterTotals[letter] > positiveCount) {
                    maxLetterCounts[letter] = positiveCount;
                }
            });
        });

        // Ensure minLetterCounts accounts for distinct exactPositions of the same letter
        const exactCountByLetter = {};
        exactPositions.forEach(ch => {
            if (ch) exactCountByLetter[ch] = (exactCountByLetter[ch] || 0) + 1;
        });
        Object.keys(exactCountByLetter).forEach(ch => {
            minLetterCounts[ch] = Math.max(minLetterCounts[ch] || 0, exactCountByLetter[ch]);
        });

        return {
            exactPositions,
            forbiddenPositions,
            minLetterCounts,
            maxLetterCounts
        };
    }

    // Check if a 5-letter word is in the 10,000 common words dictionary
    isValidDictionaryWord(word) {
        if (!word || typeof word !== "string" || word.length !== 5) return false;
        return this.validWordSet.has(word.toUpperCase());
    }

    // Validate if a candidate 5-letter word satisfies all active clues
    validateWordForClue(word, clueState = null) {
        const upper = (word || "").toUpperCase();
        if (upper.length !== 5) {
            return { valid: false, code: "LENGTH", reason: "Word must be 5 letters long." };
        }
        if (!this.isValidDictionaryWord(upper)) {
            return { valid: false, code: "NOT_IN_LIST", reason: `"${upper}" is not in the 10,000 common words list.` };
        }

        const state = clueState || this.getClueState();

        // 1. Check exact Green / Hint position clues
        for (let i = 0; i < 5; i++) {
            if (state.exactPositions[i] && upper[i] !== state.exactPositions[i]) {
                return {
                    valid: false,
                    code: "CLUE_EXACT_POS",
                    reason: `Invalid for clue: Position ${i + 1} must be '${state.exactPositions[i]}'.`
                };
            }
        }

        // 2. Check Yellow/Gray forbidden position clues
        for (let i = 0; i < 5; i++) {
            if (state.forbiddenPositions[i].has(upper[i])) {
                return {
                    valid: false,
                    code: "CLUE_FORBIDDEN_POS",
                    reason: `Invalid for clue: '${upper[i]}' cannot be in position ${i + 1}.`
                };
            }
        }

        // Count letter occurrences in candidate word
        const candidateCounts = {};
        for (let i = 0; i < 5; i++) {
            const ch = upper[i];
            candidateCounts[ch] = (candidateCounts[ch] || 0) + 1;
        }

        // 3. Check required Yellow/Green letters (minLetterCounts)
        for (const [letter, minCount] of Object.entries(state.minLetterCounts)) {
            const actual = candidateCounts[letter] || 0;
            if (actual < minCount) {
                const msg = minCount > 1
                    ? `Invalid for clue: Word must contain at least ${minCount} '${letter}'s.`
                    : `Invalid for clue: Word must include '${letter}'.`;
                return {
                    valid: false,
                    code: "CLUE_MISSING_LETTER",
                    reason: msg
                };
            }
        }

        // 4. Check ruled-out Gray letters (maxLetterCounts)
        for (const [letter, maxCount] of Object.entries(state.maxLetterCounts)) {
            const actual = candidateCounts[letter] || 0;
            if (actual > maxCount) {
                const msg = maxCount === 0
                    ? `Invalid for clue: Letter '${letter}' was already ruled out.`
                    : `Invalid for clue: Word can contain at most ${maxCount} '${letter}'.`;
                return {
                    valid: false,
                    code: "CLUE_RULED_OUT_LETTER",
                    reason: msg
                };
            }
        }

        return {
            valid: true,
            code: "VALID",
            reason: `✓ "${upper}" is a valid word & matches all clues!`
        };
    }

    // Return all words from the 10,000 list that satisfy the current clues
    getMatchingWordsForClues(clueState = null) {
        const state = clueState || this.getClueState();
        const guessedSet = new Set(this.guesses);
        return this.wordList.filter(w => {
            if (guessedSet.has(w) && w !== this.currentWord) return false;
            return this.validateWordForClue(w, state).valid;
        });
    }

    // Reveal a positional letter clue ONLY when the user clicks the "💡 Clue" button
    revealClue() {
        if (!this.isPlaying || this.gameOver || !this.currentWord) {
            if (window.showToast) window.showToast("Click Start Game first to use a clue!", "💡");
            return;
        }

        const clueState = this.getClueState();
        const unrevealed = [];
        for (let i = 0; i < 5; i++) {
            if (!clueState.exactPositions[i]) {
                unrevealed.push(i);
            }
        }

        if (unrevealed.length <= 1) {
            this.clueShown = true;
            this.updateClueAndValidationUI();
            if (window.showToast) window.showToast("4 letters are already known — solve the final letter!", "💡");
            return;
        }

        const pickIdx = unrevealed[Math.floor(Math.random() * unrevealed.length)];
        this.revealedIndices.add(pickIdx);
        this.clueShown = true;
        this.updateClueAndValidationUI();

        const revealedLetter = this.currentWord[pickIdx];
        if (window.showToast) {
            window.showToast(`Clue: Position ${pickIdx + 1} is '${revealedLetter}'!`, "💡");
        }
        if (window.sounds) window.sounds.score();
    }

    updateClueAndValidationUI() {
        if (!this.isPlaying || !this.currentWord) return;

        const clueState = this.getClueState();
        const matchingWords = this.getMatchingWordsForClues(clueState);

        if (this.validCountEl) {
            this.validCountEl.textContent = matchingWords.length.toLocaleString();
        }

        // Only display the clue banner if the user explicitly clicked "💡 Clue"
        if (!this.cluePanel) return;
        if (!this.clueShown) {
            this.cluePanel.classList.add("hidden");
            return;
        }

        this.cluePanel.classList.remove("hidden");

        const patternStr = clueState.exactPositions.map(ch => ch || "_").join(" ");
        if (this.cluePatternEl) {
            this.cluePatternEl.textContent = `💡 Clue: ${patternStr}`;
        }

        if (this.clueTextEl) {
            this.clueTextEl.textContent = this.getWordBaseClue();
        }
    }

    shakeCurrentRow() {
        const currentRow = this.guesses.length;
        const rowEl = document.querySelector(`.wordle-row:nth-child(${currentRow + 1})`);
        if (rowEl) {
            rowEl.classList.remove("shake");
            void rowEl.offsetWidth;
            rowEl.classList.add("shake");
        }
        if (window.sounds) window.sounds.lostLife();
    }

    handleKeyPress(event) {
        if (!this.isPlaying || this.gameOver) return;
        if (window.arcadeApp && !window.arcadeApp.isGameActive("wordle")) return;
        if (event.ctrlKey || event.metaKey || event.altKey) return;

        if (event.key === "Enter") {
            event.preventDefault();
            this.submitGuess();
        } else if (event.key === "Backspace") {
            event.preventDefault();
            this.currentGuess = this.currentGuess.slice(0, -1);
            this.updateBoard();
            if (window.sounds) window.sounds.move();
        } else if (event.key.length === 1 && /[a-zA-Z]/.test(event.key)) {
            if (this.currentGuess.length < 5) {
                this.currentGuess += event.key.toUpperCase();
                this.updateBoard();
                if (window.sounds) window.sounds.move();
            }
        }
    }

    handleKeyClick(key) {
        if (!this.isPlaying || this.gameOver) return;

        if (key === "↵" || key === "ENTER") {
            this.submitGuess();
        } else if (key === "⌫" || key === "BACKSPACE") {
            this.currentGuess = this.currentGuess.slice(0, -1);
            this.updateBoard();
            if (window.sounds) window.sounds.move();
        } else if (this.currentGuess.length < 5) {
            this.currentGuess += key;
            this.updateBoard();
            if (window.sounds) window.sounds.move();
        }
    }

    updateBoard() {
        const currentRow = this.guesses.length;
        const cells = document.querySelectorAll(`.wordle-row:nth-child(${currentRow + 1}) .wordle-cell`);

        cells.forEach((cell, index) => {
            cell.textContent = this.currentGuess[index] || "";
            cell.className = "wordle-cell";
        });
    }

    submitGuess() {
        if (this.currentGuess.length !== 5) {
            this.shakeCurrentRow();
            if (window.showToast) window.showToast("Word must be 5 letters!", "⚠️");
            return;
        }

        const guess = this.currentGuess.toUpperCase();

        // 1. Validate against 10,000 most common words dictionary
        if (!this.isValidDictionaryWord(guess)) {
            this.shakeCurrentRow();
            if (window.showToast) window.showToast(`"${guess}" is not in the 10,000 common words list!`, "❌");
            return;
        }

        // 2. Prevent duplicate guess in the same game
        if (this.guesses.includes(guess)) {
            this.shakeCurrentRow();
            if (window.showToast) window.showToast(`You already guessed "${guess}"!`, "⚠️");
            return;
        }

        // 3. Validate whether the word is valid for the active clues
        const clueValidation = this.validateWordForClue(guess);
        if (this.strictClueMode && !clueValidation.valid) {
            this.shakeCurrentRow();
            if (window.showToast) window.showToast(clueValidation.reason, "🛡️");
            return;
        }

        this.guesses.push(guess);

        const currentRow = this.guesses.length - 1;
        const cells = document.querySelectorAll(`.wordle-row:nth-child(${currentRow + 1}) .wordle-cell`);

        const letterCounts = {};
        for (let i = 0; i < this.currentWord.length; i++) {
            const letter = this.currentWord[i];
            letterCounts[letter] = (letterCounts[letter] || 0) + 1;
        }

        // Exact matches (Green)
        for (let i = 0; i < 5; i++) {
            cells[i].textContent = guess[i];
            if (guess[i] === this.currentWord[i]) {
                cells[i].classList.add("correct");
                letterCounts[guess[i]]--;
            }
        }

        // Partial matches (Yellow) & Absent (Gray)
        for (let i = 0; i < 5; i++) {
            if (guess[i] !== this.currentWord[i]) {
                if (this.currentWord.includes(guess[i]) && letterCounts[guess[i]] > 0) {
                    cells[i].classList.add("present");
                    letterCounts[guess[i]]--;
                } else {
                    cells[i].classList.add("absent");
                }
            }
        }

        // Update keyboard colors accurately per cell status
        const keys = document.querySelectorAll(".key");
        for (let i = 0; i < 5; i++) {
            const gChar = guess[i];
            const isCorrect = cells[i].classList.contains("correct");
            const isPresent = cells[i].classList.contains("present");
            keys.forEach(key => {
                if (key.textContent !== gChar) return;
                if (isCorrect) {
                    key.classList.remove("present", "absent");
                    key.classList.add("correct");
                } else if (isPresent && !key.classList.contains("correct")) {
                    key.classList.remove("absent");
                    key.classList.add("present");
                } else if (!key.classList.contains("correct") && !key.classList.contains("present")) {
                    key.classList.add("absent");
                }
            });
        }

        this.currentGuess = "";

        if (guess === this.currentWord) {
            this.gameOver = true;
            if (typeof wordleTimer !== "undefined") wordleTimer.stop();
            this.played++;
            this.streak++;
            this.saveStats();
            this.updateClueAndValidationUI();
            const timeStr = document.getElementById("wordleTimer") ? document.getElementById("wordleTimer").textContent : "00:00";
            if (window.celebrateWin) {
                setTimeout(() => {
                    window.celebrateWin({
                        title: "SPLENDID!",
                        subtitle: `You deciphered "${this.currentWord}" in ${this.guesses.length} ${this.guesses.length === 1 ? "try" : "tries"}!`,
                        trophy: "🔤",
                        stats: [
                            { label: "Word", val: this.currentWord },
                            { label: "Guesses", val: `${this.guesses.length}/6` },
                            { label: "Win Streak", val: this.streak },
                            { label: "Time", val: timeStr }
                        ],
                        onRestart: () => this.newGame()
                    });
                }, 350);
            } else if (window.sounds) {
                window.sounds.win();
            }
        } else if (this.guesses.length === this.maxGuesses) {
            this.gameOver = true;
            if (typeof wordleTimer !== "undefined") wordleTimer.stop();
            this.played++;
            this.streak = 0;
            this.saveStats();
            this.updateClueAndValidationUI();
            if (window.showGameOverModal) {
                setTimeout(() => {
                    window.showGameOverModal({
                        title: "WORD MISSED",
                        subtitle: `The secret word was "${this.currentWord}".`,
                        icon: "💡",
                        stats: [
                            { label: "Correct Word", val: this.currentWord },
                            { label: "Games Played", val: this.played },
                            { label: "Streak Reset", val: "0" }
                        ],
                        onRestart: () => this.newGame()
                    });
                }, 350);
            } else if (window.sounds) {
                window.sounds.gameOver();
            }
        } else {
            this.updateBoard();
            this.updateClueAndValidationUI();
            if (window.sounds) window.sounds.score();
        }
    }

    saveStats() {
        const pEl = document.getElementById("wordlePlayed");
        if (pEl) pEl.textContent = this.played;
        const sEl = document.getElementById("wordleStreak");
        if (sEl) sEl.textContent = this.streak;

        if (window.ScoreStorage) {
            window.ScoreStorage.set("wordlePlayed", this.played);
            window.ScoreStorage.set("wordleStreak", this.streak);
        }
    }
}

